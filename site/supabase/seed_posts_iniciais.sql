## O que o CPL mostra e o que ele esconde

O CPL é uma conta simples: investimento em mídia dividido pelo número de leads. Ele é útil para comparar campanhas e criativos entre si. O problema começa quando ele vira a métrica que define se o marketing está dando certo.

Um lead barato pode:

- não ter o perfil de quem compra;
- não responder quando o comercial chama;
- demorar tanto para ser atendido que esfria;
- comprar um ticket baixo que não paga o custo de aquisição.

Em todos esses casos o CPL continua lindo. Quem paga a conta é a margem.

## O caminho inteiro: do dinheiro investido ao dinheiro que volta

Para saber se uma operação de marketing é lucrativa, é preciso olhar o caminho completo, etapa por etapa. Na prática, a leitura mínima tem cinco números:

1. **CPL**: quanto custa cada lead.
2. **Taxa de qualificação**: quantos leads têm perfil real de compra.
3. **Taxa de conversão em venda**: quantos dos qualificados viram cliente.
4. **CAC**: quanto custa, no fim, cada cliente conquistado.
5. **Margem por venda**: quanto sobra de cada venda para pagar esse CAC.

Quando a gente olha só o primeiro número, está decidindo com 20% da informação.

## Um exemplo com números fictícios

Imagine duas campanhas, cada uma com R$ 10.000 investidos. Os números abaixo são ilustrativos, só para mostrar a lógica.

| | Campanha A | Campanha B |
|---|---|---|
| Leads | 1.000 | 400 |
| CPL | R$ 10 | R$ 25 |
| Leads qualificados | 10% (100) | 40% (160) |
| Vendas | 10 | 24 |
| CAC | R$ 1.000 | R$ 417 |

Olhando só o CPL, a campanha A parece duas vezes e meia melhor. Olhando a operação, a campanha B traz mais que o dobro de vendas com o mesmo dinheiro e um custo por cliente menor que a metade. Se a margem por venda for de R$ 600, a campanha A dá prejuízo em cada cliente e a B dá lucro.

## Por que tanta empresa olha só o CPL

Não é preguiça. Na maioria das vezes, é falta de estrutura para enxergar o resto:

- o **rastreamento** não liga o lead à venda;
- o **CRM** não registra a origem de cada oportunidade;
- marketing e comercial **não usam o mesmo critério** do que é um lead qualificado;
- ninguém calculou o **CPA máximo**, o quanto dá para pagar por cliente sem perder dinheiro.

Sem isso, o único número disponível é o do gerenciador de anúncios. E a empresa passa a otimizar o que consegue medir, não o que importa.

## Como começar a medir do jeito certo

Não precisa de nenhum sistema caro para dar o primeiro passo:

- **Registre a origem de cada lead** com UTMs nos links e um campo de origem no CRM ou na planilha.
- **Defina com o comercial** o que é um lead qualificado e marque isso em cada contato.
- **Feche o ciclo**: toda venda precisa voltar para a origem que gerou o lead.
- **Calcule o seu CPA máximo** a partir do ticket médio e da margem. Tudo que custar acima disso está tirando dinheiro do caixa.

Com esses quatro passos, a pergunta deixa de ser "qual campanha tem o CPL mais baixo?" e vira "qual campanha traz cliente com lucro?".

